/**
 * Función que mapea productos provenientes de Prisma a EcommerceProduct
 */
export function mapPrismaProductToEcommerceProduct(prismaProd: any): EcommerceProduct {
  const imageList: string[] = [];
  if (Array.isArray(prismaProd.images) && prismaProd.images.length > 0) {
    for (const img of prismaProd.images) {
      if (img?.url && typeof img.url === "string") {
        imageList.push(img.url);
      }
    }
  } else if (prismaProd.imageUrl) {
    imageList.push(prismaProd.imageUrl);
  }

  const primaryImg = imageList[0] || SHARED_IMAGE;
  const rawPrice = Number(prismaProd.price || 0);

  // Mapear talles y disponibilidad desde variants
  const sizeMap = new Map<string, boolean>();
  const colorsSet = new Set<string>();

  if (Array.isArray(prismaProd.variants)) {
    for (const v of prismaProd.variants) {
      if (v.size) {
        const available = (v.stockStore || 0) + (v.stockWarehouse || 0) > 0;
        sizeMap.set(v.size, (sizeMap.get(v.size) || false) || available);
      }
      if (v.color) {
        colorsSet.add(v.color);
      }
    }
  }

  const sizes = Array.from(sizeMap.entries()).map(([size, inStock]) => ({
    size,
    inStock,
  }));

  const totalStock = Array.isArray(prismaProd.variants)
    ? prismaProd.variants.reduce(
        (sum: number, v: any) => sum + (v.stockStore || 0) + (v.stockWarehouse || 0),
        0
      )
    : 10;

  return {
    id: prismaProd.id,
    name: prismaProd.name,
    brand: prismaProd.brand?.name || "MATACOS",
    category: prismaProd.category?.name || "General",
    discipline: prismaProd.discipline?.name || "Deportes",
    price: rawPrice,
    image: primaryImg,
    images: imageList.length > 0 ? imageList : [primaryImg],
    description: prismaProd.description || undefined,
    highlights: Array.isArray(prismaProd.highlights) ? prismaProd.highlights : undefined,
    specs: prismaProd.specs && typeof prismaProd.specs === "object" ? prismaProd.specs : undefined,
    installments: "3 y 6 cuotas sin interés",
    sizes: sizes.length > 0 ? sizes : undefined,
    colors: colorsSet.size > 0 ? Array.from(colorsSet) : undefined,
    inStock: totalStock > 0,
    stockCount: totalStock,
    freeShipping: rawPrice > 80000,
    storePickup: true,
    cashTransferDiscountPercent: 10,
  };
}
