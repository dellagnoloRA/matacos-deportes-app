export function getProvinces(): string[] {
  return ARGENTINA_PROVINCES_DATA.map((p) => p.province).sort((a, b) =>
    a.localeCompare(b, "es", { sensitivity: "base" })
  );
}

export function getLocalitiesForProvince(provinceName: string): string[] {
  if (!provinceName) return [];
  const found = ARGENTINA_PROVINCES_DATA.find(
    (p) => p.province.toLowerCase() === provinceName.trim().toLowerCase()
  );
  if (!found) return [];
  return [...found.localities].sort((a, b) =>
    a.localeCompare(b, "es", { sensitivity: "base" })
  );
}

